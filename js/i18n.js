  const sortedPhrases = phrases.slice().sort((left, right) => right[0].length - left[0].length);
  const textRecords = new WeakMap();
  const attributeRecords = new WeakMap();
  let activeLanguage = 'vi';

  function translateText(source) {
    if (activeLanguage !== 'en') return source;
    let translated = source;
    for (const [vietnamese, english] of sortedPhrases) translated = translated.replaceAll(vietnamese, english);
    return translated;
  }

  function translateTextNode(node) {
    if (!node.nodeValue || !node.nodeValue.trim()) return;
    let record = textRecords.get(node);
    if (!record || node.nodeValue !== record.output) record = { source: node.nodeValue, output: node.nodeValue };
    const output = translateText(record.source);
    record.output = output;
    textRecords.set(node, record);
    if (node.nodeValue !== output) node.nodeValue = output;
  }

  function translateAttribute(element, name) {
    let records = attributeRecords.get(element);
    if (!records) {
      records = new Map();
      attributeRecords.set(element, records);
    }
    const current = element.getAttribute(name);
    if (current === null) return;
    let record = records.get(name);
    if (!record || current !== record.output) record = { source: current, output: current };
    const output = translateText(record.source);
    record.output = output;
    records.set(name, record);
    if (current !== output) element.setAttribute(name, output);
  }

  function translateElement(element) {
    if (['SCRIPT', 'STYLE', 'TEXTAREA', 'CODE', 'PRE'].includes(element.tagName)) return;
    for (const attribute of ['placeholder', 'title', 'aria-label']) translateAttribute(element, attribute);
    for (const child of element.childNodes) {
      if (child.nodeType === Node.TEXT_NODE) translateTextNode(child);
      else if (child.nodeType === Node.ELEMENT_NODE) translateElement(child);
    }
  }

  function apply(language) {
    activeLanguage = language === 'en' ? 'en' : 'vi';
    document.documentElement.lang = activeLanguage;
    document.title = activeLanguage === 'en' ? 'NEON BREW — Night Shift Cafe' : 'NEON BREW — Tiệm cà phê tương lai';
    if (document.body) translateElement(document.body);
  }

  const observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === 'characterData') translateTextNode(record.target);
      else if (record.type === 'attributes') translateAttribute(record.target, record.attributeName);
      else for (const node of record.addedNodes) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
        else if (node.nodeType === Node.ELEMENT_NODE) translateElement(node);
      }
    }
  });
  observer.observe(document.body, {subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['placeholder','title','aria-label']});

  window.NEON_BREW_I18N = { apply };
